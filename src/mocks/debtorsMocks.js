// ─── Helper: agrupa cobranças por devedor ────────────────────────────────────
export function groupChargesByDebtor(charges = MOCK_SPREADSHEET_CHARGES) {
  const today = new Date();
  const map = {};

  charges.forEach((c) => {
    const key = c.cpfCnpj;
    if (!map[key]) {
      // Atribui status fictício rotativo para visualização no front-end
      const statList = ['novo', 'contatado', 'em_negociacao'];
      const randomStat = statList[Object.keys(map).length % statList.length];

      map[key] = {
        cliente: c.cliente,
        cpfCnpj: c.cpfCnpj,
        rg: c.rg,
        dataNascimento: c.dataNascimento,
        profissao: c.profissao,
        enderecoResidencial: c.enderecoResidencial,
        telefone1: c.telefone1,
        telefone2: c.telefone2,
        empreendimento: c.empreendimento,
        contrato: c.contrato,
        apto: c.apto,
        status: randomStat, // adicionado para o filtro
        totalGeral: 0,
        totalVencido: 0,
        totalFuturo: 0,
        qtdVencidas: 0,
        qtdFuturas: 0,
        charges: [],
      };
    }
    const entry = map[key];
    const vencDate = new Date(c.vencimento);
    entry.totalGeral += c.total;
    if (vencDate <= today) {
      entry.totalVencido += c.total;
      entry.qtdVencidas += 1;
    } else {
      entry.totalFuturo += c.total;
      entry.qtdFuturas += 1;
    }
    entry.charges.push(c);
  });

  return Object.values(map);
}

